            SET v_bloqueado          = 1;
            SET v_segundos_restantes = v_segundos_totales - v_segundos_transcurridos;
        END IF;
    END IF;

    -- Devolver resultado como fila (leído por Python con stored_results())
    SELECT v_bloqueado AS bloqueado, v_segundos_restantes AS segundos_restantes;
